/** Bounding box da bacia: [[sul, oeste], [norte, leste]] — formato Leaflet. */
export const BASIN_BOUNDS: [[number, number], [number, number]] = (() => {
  let minLat = 90, maxLat = -90, minLon = 180, maxLon = -180;
  for (const [lon, lat] of BASIN_RING) {
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
  }
  return [
    [minLat, minLon],
    [maxLat, maxLon],
  ];
})();

/**
 * Teste ponto-em-polígono (ray casting).
 * Retorna true se a coordenada estiver dentro do limite da bacia.
 */
export function isInsideBasin(lat: number, lon: number): boolean {
  let inside = false;
  for (let i = 0, j = BASIN_RING.length - 1; i < BASIN_RING.length; j = i++) {
    const [xi, yi] = BASIN_RING[i];
    const [xj, yj] = BASIN_RING[j];
    const intersect = yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}
